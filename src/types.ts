/** Part-of-speech / role. Drives Modified Fitzgerald Key colour coding. */
export type WordType =
  | 'pronoun'
  | 'verb'
  | 'descriptor'
  | 'noun'
  | 'social'
  | 'question'
  | 'preposition'
  | 'negation'
  | 'determiner'
  | 'conjunction'
  | 'folder'
  | 'misc';

/** Special behaviours a button can have instead of adding a word. */
export type ButtonAction =
  | 'keyboard'
  | 'phrases'
  | 'tools'
  | 'home'
  | 'back'
  | 'speak'
  | 'clear'
  | 'backspace'
  | 'morph-s'
  | 'morph-ing'
  | 'morph-ed'
  | 'forms'
  | 'attention';

/**
 * Symbol reference:
 *  - `a:1234`  bundled / remote ARASAAC pictogram id
 *  - `e:🍎`    emoji
 *  - `img:xyz` user image stored in the asset DB
 */
export type SymbolRef = string;

export interface AACButton {
  id: string;
  label: string;
  /** Text spoken / added to the message if different from the label. */
  speak?: string;
  symbol?: SymbolRef;
  type: WordType;
  /** Background colour override (CSS colour). */
  color?: string;
  /** Opens this board instead of adding a word. */
  link?: string;
  action?: ButtonAction;
  /** Asset id of a recorded audio clip played instead of TTS. */
  audio?: string;
  /** Masked: keeps its place but is not shown (motor planning). */
  hidden?: boolean;
  /** Explicit word forms (otherwise generated by morphology rules). */
  forms?: string[];
  /** Speak immediately and do not add to the message bar (e.g. "Hey!"). */
  speakOnly?: boolean;
  /** Original English word of a built-in button (lets language switches round-trip exactly). */
  key?: string;
}

export type Cell = AACButton | null;

export interface Board {
  id: string;
  name: string;
  cols: number;
  rows: number;
  /** Row-major, length === cols * rows. Positions are stable. */
  cells: Cell[];
  symbol?: SymbolRef;
  /** Original English name of a built-in board (language round-trips). */
  key?: string;
}

export interface Phrase {
  id: string;
  text: string;
  symbol?: SymbolRef;
  category: string;
  audio?: string;
}

export interface ScheduleStep {
  id: string;
  label: string;
  symbol?: SymbolRef;
  done?: boolean;
  /** Optional length of the activity (starts the visual timer from "Now"). */
  minutes?: number;
}

export interface Schedule {
  id: string;
  name: string;
  steps: ScheduleStep[];
}

export interface AboutMe {
  enabled: boolean;
  text: string;
  contacts: string;
}

export type Theme = 'light' | 'dark' | 'contrast';
export type Style = 'playful' | 'clean';
export type ColorMode = 'fill' | 'border' | 'none';
export type LockMethod = 'hold' | 'pin' | 'math' | 'none';

export interface Settings {
  /** Communication language: board words, grammar, keyboard, voice. */
  language: 'en' | 'es' | 'fr' | 'pt';
  /** Language of menus and settings ('auto' = same as the communication language). */
  uiLanguage: 'auto' | 'en' | 'es' | 'fr' | 'pt';
  /** Optional second language shown small on each button (bilingual homes). */
  secondLabel: '' | 'en' | 'es' | 'fr' | 'pt';
  /** Spanish: conjugate a verb automatically after a subject pronoun (yo + querer → quiero). */
  autoConjugate: boolean;
  // Voice
  voiceURI?: string;
  voiceIndex?: number;
  /** Native voice name (indexes can shift between devices/engine updates). */
  voiceName?: string;
  /** Pronunciation fixes: written word → how to say it (applies to everything spoken). */
  pronunciations?: Record<string, string>;
  rate: number;
  pitch: number;
  volume: number;
  lang: string;
  // Speaking behaviour
  speakOnTap: boolean;
  speakFolders: boolean;
  clearAfterSpeak: boolean;
  returnHome: boolean;
  // Display
  theme: Theme;
  style: Style;
  colorMode: ColorMode;
  showLabels: boolean;
  labelTop: boolean;
  textCase: 'as-is' | 'lower' | 'upper';
  fontScale: number;
  gap: number;
  showQuickBar: boolean;
  showSymbolsInBar: boolean;
  reduceMotion: boolean;
  keepAwake: boolean;
  babble: boolean;
  // Navigation items visible to the user
  showKeyboardNav: boolean;
  showPhrasesNav: boolean;
  showToolsNav: boolean;
  // Touch accommodations
  holdMs: number;
  debounceMs: number;
  /** Activate on finger down (fast) instead of on release. */
  pressOnDown: boolean;
  // Feedback
  clickSound: boolean;
  haptics: boolean;
  // Scanning
  scanning: boolean;
  scanMode: 'auto' | 'step';
  scanPattern: 'row-col' | 'linear';
  scanMs: number;
  scanSpeak: boolean;
  // Head / eye pointer & dwell
  pointer: 'off' | 'dwell' | 'head' | 'eyes';
  dwellMs: number;
  pointerSensitivity: number;
  pointerSmoothing: number;
  blinkSelect: boolean;
  gazeCalibration?: number[][];
  // Keyboard
  keyboardLayout: 'qwerty' | 'abc' | 'azerty';
  learnWords: boolean;
  /** Fetch a pictogram from arasaac.org when its bundled copy is missing (e.g. on imported boards). */
  downloadSymbols: boolean;
  // The grown-up lock and PIN are app-wide since v0.5: see AppData.grownUpLock.
  // Data
  logging: boolean;
  /** Recent sentences: kept ('on'), kept until Caleb closes ('session'), or not kept ('off'). */
  keepRecent: 'on' | 'session' | 'off';
}

/** A recently spoken sentence (Phrases → Recent). */
export interface HistoryEntry {
  /** Stable id (filled in on load for older saves). */
  id?: string;
  text: string;
  t: number;
}

export interface Profile {
  id: string;
  name: string;
  layout: LayoutId;
  boards: Record<string, Board>;
  rootId: string;
  quickBar: AACButton[];
  phrases: Phrase[];
  phraseCategories: string[];
  schedules: Schedule[];
  aboutMe: AboutMe;
  settings: Settings;
  /** Learned words for keyboard prediction (word → count). */
  lexicon: Record<string, number>;
  history: HistoryEntry[];
  createdAt: number;
  /** Last change (used to merge profiles when syncing between devices). */
  updatedAt?: number;
}

export type LayoutId = 'big' | 'compact' | 'medium' | 'full';

/** A picture saved in the symbol library (built-in or created by the family). */
export interface LibrarySymbol {
  id: string;
  label: string;
  symbol: SymbolRef;
  type?: WordType;
}

/** A symbol category (shown as a folder with an icon). */
export interface LibraryCategory {
  id: string;
  name: string;
  icon?: SymbolRef;
  symbols: LibrarySymbol[];
}

/** The family's own symbol library, shared by all profiles on the device. */
export interface SymbolLibrary {
  /** Categories created by the family. */
  categories: LibraryCategory[];
  /** Extra symbols the family added to built-in categories (category id → symbols). */
  additions: Record<string, LibrarySymbol[]>;
}

/** The grown-up lock: one for the whole app, so switching or adding profiles can't get round it. */
export interface GrownUpLock {
  lock: LockMethod;
  /** 4–6 digits, required when `lock` is 'pin'. */
  pin?: string;
  /** Set once when profiles had different PINs: name of the profile whose PIN was kept. */
  pinNotice?: string;
}

export interface AppData {
  version: number;
  profiles: Profile[];
  activeProfileId: string;
  onboarded: boolean;
  library: SymbolLibrary;
  /** App-wide grown-up lock (v0.5+). Older saves kept it per profile; migrate() moves it here. */
  grownUpLock?: GrownUpLock;
}

export interface MessageWord {
  id: string;
  text: string;
  /** Dictionary form when the text was inflected automatically (querer → quiero). */
  base?: string;
  symbol?: SymbolRef;
  type?: WordType;
  audio?: string;
}
