/**
 * Brazilian Portuguese (pt-BR) translations of the default vocabulary in
 * `../vocab.ts`.
 *
 * Kept dependency-free, like vocab.ts, so Node scripts can import it with
 * type stripping.
 *
 * Conventions:
 * - Keys are the exact English label as produced by `parseSpec()` (the text
 *   before any `|`, `@`, `#` or `~`, without the `x:` type prefix).
 * - A value is the Portuguese label, or `[label, spoken]` when the spoken text
 *   should differ from the button label.
 * - Verbs are infinitives (querer, ir, comer); the app conjugates them after a
 *   subject pronoun. "like" is "gostar" (the app builds "gosto de").
 *   Multi-word verbs keep their complement (andar de, correr atrás, fazer xixi).
 * - Nouns are singular without an article; adjectives are masculine singular.
 * - Pronouns follow everyday Brazilian usage: você (not tu), meu/seu,
 *   dele/dela/deles.
 *
 * Deliberate exceptions and ambiguities (one English label shared by several
 * categories gets one Portuguese word):
 * - Quick-bar protest words use the form that is said alone: help → "ajuda",
 *   stop → "para", wait → "espera", break → "pausa", "I don't know" →
 *   "não sei", all done → "acabou". finished → "terminado"; finish → "terminar".
 * - we → "nós" (one word, distinct verb forms: nós vamos / queremos, and it
 *   pairs with "nosso"). Families who prefer the spoken "a gente" can relabel.
 * - me → "mim"; him → "ele", them → "eles" (as said in Brazil: "eu vi ele"),
 *   us → "nos". his / her / their → "dele" / "dela" / "deles".
 *   my / your → "meu" / "seu"; mine / yours → "é meu" / "é seu" so they differ
 *   from my / your.
 * - hungry / thirsty / sleepy / scared / jealous → "com fome" / "com sede" /
 *   "com sono" / "com medo" / "com ciúme", so "eu estou com fome" works with
 *   am → "estar".
 * - Copulas/auxiliaries: am → "estar", is → "é", are → "são", was → "foi",
 *   were → "foram", will → "ir" (eu + ir + comer → "eu vou comer", the normal
 *   spoken future), did → "fez", does → "faz". don't → "não",
 *   can't → "não posso", won't → "não vou", isn't → "não é".
 *   no more → "chega" (what people actually say).
 * - hurts → "dói" and itchy → "coça" (3rd person: "minha cabeça dói").
 * - it → "isso" (as specified), so this / that → "este" / "esse".
 * - do → "fazer", make → "criar" (Portuguese has one verb for both; kept the
 *   two full-layout buttons distinct).
 * - play → "brincar" (the child sense); games use "jogo"; throw → "jogar".
 * - turn (core verb / "turn" in play) → "vez" (minha vez, sua vez).
 * - get → "pegar", catch → "agarrar", take → "levar".
 * - put → "colocar", put on (clothes) → "vestir".
 * - turn on / turn off → "ligar" / "desligar", so call → "chamar".
 * - walk → "andar", ride → "andar de" (andar de bicicleta).
 * - chicken (food / hen) → "frango"; fish (food / animal) → "peixe".
 * - cold (temperature / illness) → "frio"; hot → "quente".
 * - light (weight / colour) → "leve"; dark → "escuro".
 * - loud → "barulhento" and high → "alto"; louder / quieter → "mais alto" /
 *   "mais baixo" (volume).
 * - nice → "gentil", cool → "legal".
 * - clean (verb / adjective) → "limpar"; open (verb / adjective) → "abrir".
 * - hug (verb / noun in sensory) → "abraçar"; swing (noun / verb) → "balanço".
 * - work (place / verb) → "trabalhar"; gym (place / school PE) → "ginásio".
 * - bath → "tomar banho" (Brazilians mostly shower; "banho" covers both);
 *   shower → "chuveiro".
 * - when (question / conjunction) → "quando".
 * - quiet → "silêncio" (more useful on a button than "quieto").
 * - to → "a", at → "no", in → "em", from → "desde", for → "para", of → "de".
 * - Inherent duplicates: one / a → "um"; morning → "manhã" vs tomorrow →
 *   "amanhã"; afternoon and late → "tarde"; night and evening → "noite";
 *   carry and charge → "carregar"; dinner and eat dinner → "jantar";
 *   toy car and cart → "carrinho"; wallet and desk → "carteira" (the Brazilian
 *   school desk); alone and lonely → "sozinho".
 * - thank you → "obrigado" (masculine; families can change it to "obrigada").
 * - People nouns use the masculine generic (professor, amigo, enfermeiro);
 *   families can edit.
 * - Nouns that are plural or invariable in Portuguese: crianças, costas,
 *   óculos, muletas, ciências, brócolis, nuggets.
 * - Brazilian choices: suco, ônibus, celular, geladeira, banheiro, vitamina
 *   (smoothie), refrigerante, canudo, salgadinho, picolé, pula-pula,
 *   escorregador, massinha, notebook, shopping (mall), prova (test), lousa,
 *   lancheira, boné, blusa de frio, moletom, mamãe/papai, vovó/vovô,
 *   miojo (instant noodles).
 */

