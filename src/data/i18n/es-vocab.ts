/**
 * Spanish (neutral Latin-American, Mexico/US families) translations of the
 * default vocabulary in `../vocab.ts`.
 *
 * Kept dependency-free, like vocab.ts, so Node scripts can import it with
 * type stripping.
 *
 * Conventions:
 * - Keys are the exact English label as produced by `parseSpec()` (the text
 *   before any `|`, `@`, `#` or `~`, without the `x:` type prefix).
 * - A value is the Spanish label, or `[label, spoken]` when the spoken text
 *   should differ from the button label.
 * - Verbs are infinitives (querer, ir, comer); the app conjugates them after a
 *   subject pronoun. "like" is "gustar" (the app builds "me gusta").
 *   Reflexive verbs keep their -se (sentarse, despertarse, vestirse…).
 * - Nouns are singular without an article; adjectives are masculine singular.
 *
 * Deliberate exceptions and ambiguities (one English label shared by several
 * categories gets one Spanish word):
 * - Quick-bar protest words use the form that works on its own, because they
 *   are mostly said alone: help → "ayuda", stop → "alto", wait → "espera",
 *   break → "descanso" (also used for actions' "break" = romper).
 * - all done → "terminé" (said alone by beginners); finished → "terminado";
 *   finish → "terminar".
 * - hungry / thirsty / sleepy → "hambre" / "sed" / "sueño" (Spanish says
 *   "tengo hambre", not an adjective).
 * - Copulas/auxiliaries have no clean infinitive mapping: am → "estar"
 *   (feelings: "yo estoy feliz"), is → "es", are → "son", was → "fue",
 *   were → "fueron", will → "ir a", did → "hizo", does → "hace".
 *   don't → "no", can't → "no puedo", won't → "no voy a", isn't → "no es".
 * - hurts → "duele" (works like gustar: "me duele"); love → "amar"
 *   ("encantar" would be more idiomatic for things but needs gustar-style
 *   handling).
 * - it → "eso" (as specified), so that → "ese" to keep the two core buttons
 *   distinct.
 * - do → "hacer", make → "crear" (Spanish has one verb for both; kept the two
 *   full-layout buttons distinct).
 * - turn (verb in core layouts, "turn" in play) → "turno" (taking turns).
 * - orange → "naranja" (fruit and colour are the same word).
 * - chicken (food / hen) → "pollo"; fish (food / animal) → "pescado".
 * - cold (temperature / illness) → "frío"; hot → "caliente".
 * - light (weight / colour) → "ligero"; dark → "oscuro".
 * - clean (verb / adjective) → "limpiar"; open (verb / adjective) → "abrir".
 * - hug (verb / noun in sensory) → "abrazar"; swing (noun / verb) → "columpio".
 * - work (place / verb) → "trabajar" ("ir a trabajar" reads naturally).
 * - call (verb / phone call) → "llamar".
 * - when (question / conjunction) → "cuándo".
 * - quiet → "silencio" (more useful on a button than "callado").
 * - morning and tomorrow are both "mañana"; afternoon and late are both
 *   "tarde"; night and evening are both "noche" — inherent in Spanish.
 * - brown → "café" (Mexico), same as coffee.
 * - his / her / their → "de él" / "de ella" / "de ellos" (instead of three
 *   identical "su" buttons). him → "lo", them → "los", us → "nos".
 * - in → "en", at → "a" (and to → "a"); on → "encima"; off → "fuera".
 * - toy car and cart are both "carrito".
 * - People nouns use the masculine generic (maestro, amigo, enfermero);
 *   families can edit.
 * - A few nouns stay plural because the singular is unnatural: frijoles,
 *   papas fritas, papitas, palomitas, nuggets, burbujas, tijeras, lentes,
 *   audífonos, matemáticas, ciencias, muletas, niños.
 * - Regional choices for Mexico/US: jugo, popote, alberca, carro, chamarra,
 *   cobija, refri, lonchera, pizarrón, resbaladilla, chícharo, crema de
 *   cacahuate, pastel, dona, paleta, papa, recámara, celular, computadora.
 */

